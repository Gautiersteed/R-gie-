/*
 * Principe : le clip est d'abord "préparé" une fois (extrait début→fin,
 * ré-encodé aux réglages YouTube, keyframes toutes les 2 s) puis mis en
 * cache. La diffusion réelle se fait ensuite en `-c copy` : le serveur
 * ne fait que pousser des octets, donc un CPU quasi nul et aucune
 * dérive de qualité, même sur un petit serveur.
 */

const schedule = { timer: null, startAt: 0, clipId: null, options: null };

function cachePath(clip, opts) {
  const preset = PRESETS[opts.preset] || PRESETS['720p30'];
  const fps = clamp(Number(opts.fps) || preset.fps, 5, 60);
  const height = clamp(Number(opts.height) || preset.height, 144, 1440);
  const vbr = clamp(Number(opts.videoBitrate) || preset.vbr, 200, 12000);
  const s = Number(clip.start) || 0;
  const e = clip.end || clip.duration || 0;
  const [cw, ch] = dimsFor(opts.ratio || '16:9', height);
  if (opts.compatOnly) {
    return path.join(CACHE_DIR, `${clip.id}__compat_${s.toFixed(1)}-${e.toFixed(1)}.mp4`);
  }
  return path.join(CACHE_DIR, `${clip.id}__${cw}x${ch}_${Math.round(fps)}_${Math.round(vbr)}k_${s.toFixed(1)}-${e.toFixed(1)}.mp4`);
}

/** Prépare (ou récupère en cache) le clip aux réglages cibles. */
/**
 * Peut-on diffuser le fichier tel quel, sans le ré-encoder ?
 * Indispensable pour les très longues vidéos (11 h) : cela évite un fichier
 * de cache de plusieurs Go et des heures de préparation.
 */
const DIRECT_AUDIO = new Set(['aac', 'mp3']);

/* ---- Compatibilité YouTube en lecture directe ---------------------
   YouTube n'accepte un flux copié tel quel que si :
     - H.264 en 8 bits yuv420p (Profil High/Main/Baseline) ;
     - une image-clé au moins toutes les 4 s (l'idéal : 2 s).
   Sinon son transcodeur n'arrive pas à découper le flux : le direct
   apparaît « EN DIRECT » avec un lecteur GRIS.                      */

function intervalleCles(file, fenetre = 90) {
  try {
    const r = spawnSync(FFPROBE, [
      '-v', 'error', '-select_streams', 'v:0', '-skip_frame', 'nokey',
      '-read_intervals', '%+' + fenetre,
      '-show_entries', 'frame=pts_time', '-of', 'csv=p=0', file,
    ], { encoding: 'utf8', timeout: 30000, maxBuffer: 4 * 1024 * 1024 });
    if (r.status !== 0) return null;
    const t = String(r.stdout || '').split('\n').map((x) => Number(x.trim()))
      .filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
    if (t.length < 2) return t.length === 1 ? fenetre : null;  // une seule clé = très long
    const ecarts = [];
    for (let i = 1; i < t.length; i++) ecarts.push(t[i] - t[i - 1]);
    ecarts.sort((a, b) => a - b);
    return ecarts[Math.floor(ecarts.length / 2)];
  } catch { return null; }
}

function compatYoutube(clip) {
  const raisons = [];
  if (!clip) return { ok: false, raisons: ['clip inconnu'] };
  const src = clipPath(clip);
  if (!src || !fs.existsSync(src)) return { ok: false, raisons: ['fichier absent'] };

  if (clip.videoCodec !== 'h264') raisons.push('codec vidéo ' + (clip.videoCodec || '?') + ' au lieu de h264');

  // Paramètres fins : lus une seule fois puis mémorisés dans la bibliothèque
  if (!clip.pixFmt || clip.profile === undefined || clip.gopSec === undefined) {
    try {
      const info = probe(src);
      clip.profile = info.profile;
      clip.pixFmt = info.pixFmt;
      clip.gopSec = intervalleCles(src);
      saveLibrary();
    } catch { return { ok: false, raisons: ['fichier illisible'] }; }
  }

  const pix = String(clip.pixFmt || '');
  if (!/^yuvj?420p$/.test(pix)) raisons.push('pixel format ' + (pix || 'inconnu') + ' au lieu de yuv420p');

  const prof = String(clip.profile || '').toLowerCase();
  if (prof && !/baseline|main|high/.test(prof)) raisons.push('profil « ' + clip.profile + ' » non pris en charge');
  if (/10$|422|444/.test(prof)) raisons.push('vidéo 10 bits ou 4:2:2/4:4:4 : impossible à copier');

  if (!clip.hasAudio) raisons.push('aucune piste audio');
  else if (!DIRECT_AUDIO.has(clip.audioCodec)) raisons.push('audio ' + clip.audioCodec + ' au lieu de aac/mp3');

  if (clip.gopSec === null) {
    raisons.push('intervalle entre images-clés illisible');
  } else if (clip.gopSec > 4) {
    raisons.push('images-clés toutes les ' + Math.round(clip.gopSec) + ' s (YouTube exige 4 s maximum)');
  }

  if (clip.width > 1920 || clip.height > 1920) raisons.push('résolution supérieure à 1920 px');
  if (clip.width % 2 || clip.height % 2) raisons.push('résolution impaire (doit être paire)');

  return { ok: raisons.length === 0, raisons };
}

function resumeCompat(clip) {
  return [clip.profile || 'profil ?', clip.pixFmt || '?',
    (clip.gopSec ? Math.round(clip.gopSec) + ' s entre images-clés' : 'intervalle inconnu')].join(', ');
}

/**
 * Le clip a-t-il déjà le rapport d'image demandé ?
 * Tolérance 5 % (une vidéo 312x570 = 0,547 est « assez verticale » pour du 9:16),
 * et on n'agrandit JAMAIS une vidéo : upscaler 11 h pour rien coûte des heures de CPU.
 */
function ratioMatches(clip, ratio, opts = {}) {
  if (!ratio || ratio === 'auto') return true;
  const r = RATIOS[ratio];
  if (!r || !clip.width || !clip.height) return true;
  const src = clip.width / clip.height;
  const want = r.w / r.h;
  if (Math.abs(src - want) / want < 0.05) return true;

  const preset = PRESETS[opts.preset] || PRESETS['720p30'];
  const targetH = clamp(Number(opts.height) || preset.height, 144, 1440);
  if (clip.height < targetH) {
    logAll('info', `Vidéo ${clip.width}×${clip.height} plus petite que le format visé `
      + `(${targetH}px de haut) : elle est diffusée telle quelle, sans agrandissement inutile.`);
    return true;
  }
  return false;
}

