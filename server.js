  if (d.recycleMin !== undefined) live.auto.recycleMin = Math.max(0, Math.min(1440, Number(d.recycleMin) || 0));
  if (d.autoBroadcast !== undefined) live.auto.autoBroadcast = Boolean(d.autoBroadcast);
